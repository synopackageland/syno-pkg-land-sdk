// Listen are the gateway's public ports on all interfaces; zero disables one.
type Listen struct {
	HTTP  int `json:"http"`
	HTTPS int `json:"https"`
}

// TLSFiles is a certificate to serve on the HTTPS port instead of the
// gateway's self-signed one.
type TLSFiles struct {
	Cert string `json:"cert"`
	Key  string `json:"key"`
}

// ClientConfig registers one relying party; its secret is generated in the
// state directory.
type ClientConfig struct {
	ID              string   `json:"id"`
	RedirectPaths   []string `json:"redirect_paths"`
	NativeRedirects []string `json:"native_redirects"`
	RequirePKCE     bool     `json:"require_pkce"`
	Roles           Roles    `json:"roles"`
}

// OIDCConfig is the oidc mode's provider.
type OIDCConfig struct {
	BrowserRedirect *BrowserRedirectConfig `json:"browser_redirect,omitempty"`
	// NativeLogin resumes DSM cold sign-in without injecting browser navigation.
	// Server-managed consumers (for example an Apache OIDC module) own redirects.
	NativeLogin bool           `json:"native_login,omitempty"`
	Browser     *BrowserConfig `json:"browser,omitempty"`
	IssuerPort  int            `json:"issuer_port"`
	Clients     []ClientConfig `json:"clients"`
	RewriteJSON []JSONRewrite  `json:"rewrite_json"`
}

// TokenConfig is the token mode's adapter command; see ExecTokens.
type TokenConfig struct {
	Command []string `json:"command"`
}

// AccountConfig turns on account deletion handling; see Deletions.
type AccountConfig struct {
	// VarDir is the package var directory, which remove actions are relative to.
	VarDir   string         `json:"var_dir"`
	OnDelete []DeleteAction `json:"on_delete"`
}

// ComposeIngress selects a deterministic package bridge endpoint.
type ComposeIngress = composeingress.Config

// Config is the gateway's JSON configuration, generated by the CLI from the
// package manifest. It holds no secrets: those live in StateDir.
type Config struct {
	External     *ExternalConfig `json:"external,omitempty"`
	PublicOrigin string          `json:"public_origin,omitempty"`
	// LaunchPath is a fixed local App URL, including an optional query/fragment.
	LaunchPath string `json:"launch_path,omitempty"`
	// NativeIngress delegates the public HTTPS listener to DSM's resource worker.
	// The CLI generates it automatically for a supported target, never from App input.
	NativeIngress    bool                       `json:"native_ingress,omitempty"`
	OperationSeconds int                        `json:"operation_seconds,omitempty"`
	StopSeconds      int                        `json:"stop_seconds,omitempty"`
	Ready            func(context.Context) bool `json:"-"`
	ContainerApp     bool                       `json:"container_app,omitempty"`
	ComposeIngress   *ComposeIngress            `json:"compose_ingress,omitempty"`
	Access           string                     `json:"access,omitempty"`
	// UpstreamAccess public delegates all App routes to upstream authentication;
	// Access and Entry still protect the embedded OIDC issuer.
	UpstreamAccess               string                             `json:"upstream_access,omitempty"`
	Groups                       []string                           `json:"groups,omitempty"`
	Entry                        string                             `json:"entry,omitempty"`
	ComposeBlocked               bool                               `json:"compose_blocked,omitempty"`
	MaxUploadBytes               int64                              `json:"max_upload_bytes,omitempty"`
	ResponseHeaderTimeoutSeconds int                                `json:"response_header_timeout_seconds,omitempty"`
	Package                      string                             `json:"package"`
	Mode                         Mode                               `json:"mode"`
	Upstream                     string                             `json:"upstream"`
	Listen                       Listen                             `json:"listen"`
	TLS                          *TLSFiles                          `json:"tls"`
	AuthorizeCGI                 string                             `json:"authorize_cgi"`
	StateDir                     string                             `json:"state_dir"`
	OptionalPassthrough          map[string]OptionalPassthroughRule `json:"optional_passthrough,omitempty"`
	Passthrough                  []string                           `json:"passthrough"`
	Redirects                    map[string]string                  `json:"redirects"`
	EmailDomain                  string                             `json:"email_domain"`
	SessionTTLSeconds            int                                `json:"session_ttl_seconds"`
	Roles                        Roles                              `json:"roles"`
	Headers                      HeaderNames                        `json:"headers"`
	OIDC                         *OIDCConfig                        `json:"oidc"`
	Token                        *TokenConfig                       `json:"token"`
	Account                      *AccountConfig                     `json:"account"`
}

var namePattern = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_.-]{0,63}$`)

// LoadConfig reads and validates a gateway configuration.
func LoadConfig(path string) (Config, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return Config{}, err
	}
	var cfg Config
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&cfg); err != nil {
		return Config{}, fmt.Errorf("%s: %w", path, err)
	}
	if err := cfg.validate(); err != nil {
		return Config{}, fmt.Errorf("%s: %w", path, err)
	}
	return cfg, nil
}

func (c Config) validate() error {
	if err := c.External.validate(); err != nil {
		return err
	}
	if c.PublicOrigin != "" && expectedOrigin(c.PublicOrigin) == "" {
		return errors.New("invalid public_origin")
	}
	if err := validateLaunchPath(c.LaunchPath); err != nil {
		return err
	}
	if err := validateUpstreamAccess(c.Mode, c.Access, c.UpstreamAccess, c.ComposeBlocked, len(c.OptionalPassthrough) > 0); err != nil {
		return err
	}
	if err := validateOptional(c.OptionalPassthrough, c.Passthrough); err != nil {
		return err
	}
	if c.OperationSeconds < 0 || c.OperationSeconds > 3600 || c.StopSeconds < 0 || c.StopSeconds > 3600 {
		return errors.New("invalid runtime budgets")
	}
	switch {
	case !namePattern.MatchString(c.Package):
		return fmt.Errorf("package %q is not a package name", c.Package)
	case !filepath.IsAbs(c.StateDir):
		return errors.New("state_dir must be absolute")
	case c.Listen.HTTP == 0 && c.Listen.HTTPS == 0:
		return errors.New("listen needs an http or https port")
	case !validPort(c.Listen.HTTP, true) || !validPort(c.Listen.HTTPS, true):
		return errors.New("listen ports must be 1-65535")
	case c.Mode == ModeOIDC && (c.OIDC == nil || !validPort(c.OIDC.IssuerPort, false) || len(c.OIDC.Clients) == 0):
		return errors.New("oidc mode needs oidc.issuer_port and at least one client")
	case c.Mode == ModeToken && (c.Token == nil || len(c.Token.Command) == 0 || !filepath.IsAbs(c.Token.Command[0])):
		return errors.New("token mode needs token.command with an absolute program path")
	}
	if c.Account != nil {
		if !filepath.IsAbs(c.Account.VarDir) {
			return errors.New("account.var_dir must be absolute")
		}
		for i, a := range c.Account.OnDelete {
			if err := a.validate(); err != nil {
				return fmt.Errorf("account.on_delete[%d]: %w", i, err)
			}
		}
	}
	if c.OIDC != nil {
		if err := c.OIDC.BrowserRedirect.validate(); err != nil {
			return err
		}
		if c.OIDC.BrowserRedirect != nil && c.Mode != ModeOIDC {
			return errors.New("oidc.browser_redirect requires oidc mode")
		}
		if c.OIDC.Browser != nil {
			if c.Mode != ModeOIDC {
				return errors.New("oidc.browser requires oidc mode")
			}
			if err := c.OIDC.Browser.validate(); err != nil {
				return err
			}
		}
		for _, client := range c.OIDC.Clients {
			if !namePattern.MatchString(client.ID) {
				return fmt.Errorf("client id %q is not a name", client.ID)
			}
		}
	}
	return nil
}

func validPort(p int, optional bool) bool {
	return (optional && p == 0) || (p > 0 && p < 65536)
}

// Issuer is the provider's loopback issuer URL.
func (c Config) Issuer() string {
	if c.OIDC == nil {
		return ""
	}
	return "http://127.0.0.1:" + strconv.Itoa(c.OIDC.IssuerPort)
}

// SessionTTL is the gateway session lifetime in header and token modes.
func (c Config) SessionTTL() time.Duration {
	if c.SessionTTLSeconds > 0 {
		return time.Duration(c.SessionTTLSeconds) * time.Second
	}
	return DefaultSessionTTL
}

// GatewayKey is the HMAC key the authorize CGI and the gateway share; both
// run as the package account.
func GatewayKey(stateDir string) ([]byte, error) {
	secret, err := loadOrCreateSecret(filepath.Join(stateDir, "gateway.key"))
	return []byte(secret), err
}

// ClientSecret is a relying party's client secret, for the app's own
// configuration.
func ClientSecret(stateDir, clientID string) (string, error) {
	if !namePattern.MatchString(clientID) {
		return "", fmt.Errorf("client id %q is not a name", clientID)
	}
	return loadOrCreateSecret(filepath.Join(stateDir, "client-"+clientID+".secret"))
}

// AdoptClientSecret persists a package-account prepared Compose seed. Existing
// provider credentials must agree; upgrades cannot silently rotate one side.
func AdoptClientSecret(stateDir, clientID, seedPath string) (string, error) {
	if !namePattern.MatchString(clientID) {
		return "", errors.New("invalid client id")
	}
	st, err := os.Lstat(seedPath)
	if err != nil || !st.Mode().IsRegular() || st.Mode().Perm()&0077 != 0 || st.Size() != 64 {
		return "", errors.New("prepared OIDC client secret unavailable")
	}
	if owner, ok := st.Sys().(*syscall.Stat_t); !ok || owner.Uid != uint32(os.Geteuid()) || owner.Nlink != 1 {
		return "", errors.New("prepared OIDC client secret must be package-owned")
	}
	f, err := os.OpenFile(seedPath, os.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_NONBLOCK, 0)
	if err != nil {
		return "", errors.New("prepared OIDC client secret unavailable")
	}
	opened, err := f.Stat()
	if err != nil || !os.SameFile(st, opened) {
		f.Close()
		return "", errors.New("prepared OIDC client secret changed")
	}
	seed, err := io.ReadAll(io.LimitReader(f, 65))
	f.Close()
	if err != nil || len(seed) != 64 || strings.IndexFunc(string(seed), func(r rune) bool { return !strings.ContainsRune("0123456789abcdef", r) }) >= 0 {
		return "", errors.New("invalid prepared OIDC client secret")
	}
	path := filepath.Join(stateDir, "client-"+clientID+".secret")
	existing, err := readPrivate(path)
	if errors.Is(err, os.ErrNotExist) {
		if err = writePrivate(path, seed); err != nil && !errors.Is(err, os.ErrExist) {
			return "", err
		}
		existing, err = readPrivate(path)
	}
	if err != nil {
		return "", err
	}
	if subtle.ConstantTimeCompare(existing, seed) != 1 {
		return "", errors.New("prepared OIDC client secret differs from retained provider state")
	}
	return string(existing), nil
}

func loadOrCreateSecret(path string) (string, error) {
	raw, err := readPrivate(path)
	if errors.Is(err, os.ErrNotExist) {
		buf := make([]byte, 32)
		rand.Read(buf)
		raw = []byte(hex.EncodeToString(buf))
		if err = writePrivate(path, raw); errors.Is(err, os.ErrExist) {
			raw, err = readPrivate(path)
		}
	}
	if err != nil {
		return "", err
	}
	if len(raw) < MinKeySize {
		return "", fmt.Errorf("%s: secret too short", path)
	}
	return string(raw), nil
}

// Deletions is the account deletion handling cfg declares, or nil.
func (c Config) Deletions() *Deletions {
	if c.Account == nil {
		return nil
	}
	return &Deletions{StateDir: c.StateDir, Passwd: "/etc/passwd", Names: NewDirectory(), Actions: c.Account.OnDelete, VarDir: c.Account.VarDir, Now: time.Now}
}

// Gateway is a configured gateway: Front serves the app's ports, Provider (in
// oidc mode) the loopback issuer, Secrets are the client secrets by id and
// Deletions, when the configuration has an account section, acts on deleted
// DSM accounts.
type Gateway struct {
	Front     *Front
	Provider  *Provider
	Secrets   map[string]string
	Deletions *Deletions
}

// Build creates the gateway's key material and handlers from cfg.
func Build(cfg Config, ports DSMPorts) (*Gateway, error) {
	key, err := GatewayKey(cfg.StateDir)
	if err != nil {
		return nil, err
	}
	gw := &Gateway{Secrets: map[string]string{}, Deletions: cfg.Deletions()}
	external := NewExternalReader(cfg)
	front := FrontConfig{
		External: external.Read,
		Ready:    cfg.Ready, ComposeIngress: cfg.ComposeIngress, Mode: cfg.Mode, Access: cfg.Access, UpstreamAccess: cfg.UpstreamAccess, Groups: cfg.Groups, Membership: NewDirectory(), ComposeBlocked: cfg.ComposeBlocked, MaxUploadBytes: cfg.MaxUploadBytes, ResponseHeaderTimeout: time.Duration(cfg.ResponseHeaderTimeoutSeconds) * time.Second, Upstream: cfg.Upstream, Key: key, AuthorizeCGI: cfg.AuthorizeCGI, DSMPorts: ports,
		Package: cfg.Package, EmailDomain: cfg.EmailDomain, Passthrough: cfg.Passthrough, Redirects: cfg.Redirects, OptionalPassthrough: cfg.OptionalPassthrough, StateDir: cfg.StateDir,
		Headers: cfg.Headers, Roles: cfg.Roles, Accounts: NewDirectory(), SessionTTL: cfg.SessionTTL(),
	}
	switch cfg.Mode {
	case ModeOIDC:
		if gw.Provider, err = cfg.provider(gw.Secrets); err != nil {
			return nil, err
		}
		front.Browser = cfg.OIDC.Browser
		front.BrowserRedirect = cfg.OIDC.BrowserRedirect
		front.PublicListen = cfg.Listen
		if cfg.NativeIngress {
			front.PublicListen = Listen{HTTPS: nativePublicPort(cfg)}
		}
		front.Provider, front.Issuer, front.RewriteJSON = gw.Provider, cfg.Issuer(), cfg.OIDC.RewriteJSON
	case ModeToken:
		front.Tokens = ExecTokens{Command: cfg.Token.Command, Timeout: cfg.operationBudget()}
	}
	if d := gw.Deletions; d != nil {
		front.SignedIn = func(s Subject) {
			if err := d.SignedIn(s); err != nil {
				log.Printf("account deletions: record uid %d: %v", s.UID, err)
			}
		}
	}
	if gw.Front, err = NewFront(front); err != nil {
		return nil, err
	}
	if gw.Deletions != nil {
		gw.Deletions.Revoke = gw.Front.RevokeUID
		gw.Deletions.Deleted = func(p PendingDeletion) {
			log.Printf("account deletions: deleted uid %d (%s), queued %s, %d earlier failed attempts", p.UID, p.Name, p.Since.Format(time.RFC3339), p.Attempts)
		}
	}
	return gw, nil
}

func (c Config) provider(secrets map[string]string) (*Provider, error) {
	signing, err := LoadOrCreateSigningKey(filepath.Join(c.StateDir, "oidc-signing.pem"))
	if err != nil {
		return nil, err
	}
	var clients []Client
	for _, cc := range c.OIDC.Clients {
		var secret string
		seed := filepath.Join("/var/packages", c.Package, "target/compose/secrets/oidc-"+cc.ID+".secret")
		if c.ContainerApp {
			if _, statErr := os.Lstat(seed); statErr == nil {
				secret, err = AdoptClientSecret(c.StateDir, cc.ID, seed)
			} else if !os.IsNotExist(statErr) {
				err = statErr
			} else {
				secret, err = ClientSecret(c.StateDir, cc.ID)
			}
		} else {
			secret, err = ClientSecret(c.StateDir, cc.ID)
		}
		if err != nil {
			return nil, err
		}
		secrets[cc.ID] = secret
		sum := sha256.Sum256([]byte(secret))
		clients = append(clients, Client{ID: cc.ID, SecretSHA256: sum[:], RedirectPaths: cc.RedirectPaths,
			NativeRedirects: cc.NativeRedirects, RequirePKCE: cc.RequirePKCE, Roles: cc.Roles})
	}
	return NewProvider(c.Issuer(), c.EmailDomain, signing, clients, time.Now)
}

// TokenAdapterTimeout bounds one run of a token adapter.
const TokenAdapterTimeout = 10 * time.Second

// ExecTokens runs an adapter program for each signed-in request. The program
// gets SYNOPKGLAND_SSO_UID, _USER and _ADMIN ("1" or "0") and prints
// {"headers": {"Name": ["value"]}}; it should cache the app sessions it mints.
type ExecTokens struct {
	Command []string
	Timeout time.Duration
}

func (e ExecTokens) Credentials(ctx context.Context, s Subject) (http.Header, error) {
	timeout := e.Timeout
	if timeout <= 0 {
		timeout = TokenAdapterTimeout
	}
	ctx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, e.Command[0], e.Command[1:]...)
	admin := "0"
	if s.Admin {
		admin = "1"
	}
	cmd.Env = append(os.Environ(), "SYNOPKGLAND_SSO_UID="+strconv.Itoa(s.UID), "SYNOPKGLAND_SSO_USER="+s.Name, "SYNOPKGLAND_SSO_ADMIN="+admin)
	out, err := boundedOutput(cmd, 64<<10)
	if err != nil {
		return nil, fmt.Errorf("token adapter: %w", err)
	}
	var reply struct{ Headers http.Header }
	if err := json.Unmarshal(out, &reply); err != nil || len(reply.Headers) == 0 {
		return nil, errors.New("token adapter: expected {\"headers\": {...}}")
	}
	return reply.Headers, nil
}

// boundedOutput runs cmd and returns its stdout, failing past limit bytes.
func boundedOutput(cmd *exec.Cmd, limit int) ([]byte, error) {
	out := &limitedBuffer{limit: limit}
	cmd.Stdout = out
	if err := cmd.Run(); err != nil {
		return nil, err
	}
	return out.Bytes(), nil
}

type limitedBuffer struct {
	bytes.Buffer
	limit int
}

func (b *limitedBuffer) Write(p []byte) (int, error) {
	if b.Len()+len(p) > b.limit {
		return 0, errors.New("output too large")
	}
	return b.Buffer.Write(p)
}

func (c Config) operationBudget() time.Duration {
	if c.OperationSeconds > 0 && c.OperationSeconds <= 3600 {
		return time.Duration(c.OperationSeconds) * time.Second
	}
	return 60 * time.Second
}
