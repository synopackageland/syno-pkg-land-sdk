// Writes the files of src/ that come from spec/: the frame types (from
// spec/bridge/v1/frames.schema.json, with json-schema-to-typescript) and the
// protocol v1 refusal and client codes an App may return (from
// spec/protocol/v1/errors.json).
// With --check it writes nothing and fails when a committed file differs.
//
// Usage: node scripts/generate.mjs [--check]
import fs from 'node:fs'
import { compile } from 'json-schema-to-typescript'

const spec = new URL('../../spec/', import.meta.url)
const src = new URL('../src/', import.meta.url)
const banner = (from) => `// Code generated by scripts/generate.mjs from spec/${from}. DO NOT EDIT.\n`

// Short names for the frame union and the definitions whose own name would
// clash with the SDK's Context or the global Error. json-schema-to-typescript
// does not pass the $defs key of a referenced definition, so they are found
// by their members.
function name(schema) {
  if (schema.oneOf) return 'Frame'
  if (schema.properties?.request_id) return 'CallContext'
  if (schema.properties?.message?.maxLength) return 'ResultError'
}

// json-schema-to-typescript reads a schema with only $comment as an object;
// $comment is not a constraint, so it goes before compiling.
function withoutComments(value) {
  if (Array.isArray(value)) return value.map(withoutComments)
  if (value === null || typeof value !== 'object') return value
  return Object.fromEntries(Object.entries(value).filter(([k]) => k !== '$comment').map(([k, v]) => [k, withoutComments(v)]))
}

async function frames() {
  const schema = JSON.parse(fs.readFileSync(new URL('bridge/v1/frames.schema.json', spec), 'utf8'))
  return compile(withoutComments(schema), 'Frame', {
    bannerComment: banner('bridge/v1/frames.schema.json'),
    additionalProperties: false,
    unreachableDefinitions: true,
    customName: name,
  })
}

function refusals() {
  const catalog = JSON.parse(fs.readFileSync(new URL('protocol/v1/errors.json', spec), 'utf8'))
  const codes = catalog.codes.filter((c) => (c.kind === 'refusal' || c.kind === 'client') && /^[A-Z][A-Z0-9_]{0,63}$/.test(c.code)).map((c) => c.code)
  return `${banner('protocol/v1/errors.json')}
// The upper-case refusal and client codes of protocol v1. An App may return
// them, so the browser's SDK can translate them.
export const protocolRefusals: ReadonlySet<string> = new Set([
${codes.map((c) => `  '${c}',\n`).join('')}])
`
}

const files = { 'frames.ts': await frames(), 'refusals.ts': refusals() }
const check = process.argv.includes('--check')
let stale = false
for (const [name, content] of Object.entries(files)) {
  const path = new URL(name, src)
  if (!check) fs.writeFileSync(path, content)
  else if (!fs.existsSync(path) || fs.readFileSync(path, 'utf8') !== content) {
    console.error(`src/${name} differs from spec/; run npm run generate`)
    stale = true
  }
}
process.exit(stale ? 1 : 0)
