// Command delegategen generates the App-facing Go and TypeScript delegate DTOs.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"
)

type schema struct {
	Type        string            `json:"type"`
	Ref         string            `json:"$ref"`
	Description string            `json:"description"`
	Format      string            `json:"format"`
	GoName      string            `json:"x-go-name"`
	GoType      string            `json:"x-go-type"`
	GoPointer   bool              `json:"x-go-pointer"`
	GoOrder     []string          `json:"x-go-order"`
	Const       *string           `json:"const"`
	Enum        []string          `json:"enum"`
	Required    []string          `json:"required"`
	Properties  map[string]schema `json:"properties"`
	Items       *schema           `json:"items"`
	AnyOf       []schema          `json:"anyOf"`
	Defs        map[string]schema `json:"$defs"`
}

func main() {
	args := os.Args[1:]
	check := len(args) > 0 && args[0] == "--check"
	if check {
		args = args[1:]
	}
	if len(args) != 1 {
		fmt.Fprintln(os.Stderr, "usage: delegategen [--check] <repository root>")
		os.Exit(2)
	}
	if err := run(args[0], check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	b, err := os.ReadFile(filepath.Join(root, "spec/delegate/v1/dtos.schema.json"))
	if err != nil {
		return err
	}
	goSource, tsSource, err := generate(b)
	if err != nil {
		return err
	}
	for _, file := range []struct {
		path string
		data []byte
	}{{"delegate/dtos_gen.go", goSource}, {"ts/src/delegate/dtos-gen.ts", tsSource}} {
		path := filepath.Join(root, file.path)
		if check {
			got, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(got, file.data) {
				return fmt.Errorf("%s is stale; run go generate ./delegate", file.path)
			}
		} else if err := os.WriteFile(path, file.data, 0644); err != nil {
			return err
		}
	}
	return nil
}

func generate(b []byte) ([]byte, []byte, error) {
	var doc schema
	if err := json.Unmarshal(b, &doc); err != nil {
		return nil, nil, err
	}
	if err := doc.validateGoTypes("schema"); err != nil {
		return nil, nil, err
	}
	var goOut, tsOut strings.Builder
	const header = "// Code generated by internal/delegategen from spec/delegate/v1/dtos.schema.json. DO NOT EDIT.\n"
	goOut.WriteString(header + "\npackage delegate\n\nimport (\"encoding/json\"; \"time\")\n\n")
	tsOut.WriteString(header + "\n")
	names := make([]string, 0, len(doc.Defs))
	for name := range doc.Defs {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		s := doc.Defs[name]
		if s.Description != "" {
			fmt.Fprintf(&tsOut, "/** %s */\n", s.Description)
			if s.GoName != "" {
				fmt.Fprintf(&goOut, "// %s: %s\n", s.GoName, s.Description)
			}
		}
		if s.Type != "object" {
			t, err := doc.typeName(s, true)
			if err != nil {
				return nil, nil, err
			}
			fmt.Fprintf(&tsOut, "export type %s = %s\n\n", name, t)
			continue
		}
		fmt.Fprintf(&goOut, "type %s struct {\n", s.GoName)
		fmt.Fprintf(&tsOut, "export interface %s {\n", name)
		// Preserve Go field order and JSON output order, including existing
		// unkeyed literals, when moving hand-written DTOs into the spec.
		fields := s.GoOrder
		if len(fields) != len(s.Properties) {
			return nil, nil, fmt.Errorf("%s: x-go-order must list every property", name)
		}
		seen := make(map[string]bool, len(fields))
		for _, field := range fields {
			if seen[field] {
				return nil, nil, fmt.Errorf("%s: duplicate property %s in x-go-order", name, field)
			}
			seen[field] = true
		}
		for _, field := range s.Required {
			if !seen[field] {
				return nil, nil, fmt.Errorf("%s: unknown required property %s", name, field)
			}
		}
		for _, field := range fields {
			p, ok := s.Properties[field]
			if !ok {
				return nil, nil, fmt.Errorf("%s: unknown required property %s", name, field)
			}
			gt, err := doc.typeName(p, false)
			if err != nil {
				return nil, nil, fmt.Errorf("%s.%s: %w", name, field, err)
			}
			tt, err := doc.typeName(p, true)
			if err != nil {
				return nil, nil, err
			}
			tag, question := field, ""
			if !slices.Contains(s.Required, field) {
				tag += ",omitempty"
				question = "?"
			}
			fmt.Fprintf(&goOut, "%s %s `json:%q`\n", goField(field), gt, tag)
			fmt.Fprintf(&tsOut, " %s%s: %s\n", field, question, tt)
		}
		goOut.WriteString("}\n\n")
		tsOut.WriteString("}\n\n")
	}
	goSource, err := format.Source([]byte(goOut.String()))
	return goSource, []byte(strings.TrimRight(tsOut.String(), "\n") + "\n"), err
}

func goField(name string) string {
	parts := strings.Split(name, "_")
	for i, part := range parts {
		if part == "id" || part == "uid" {
			parts[i] = strings.ToUpper(part)
		} else {
			parts[i] = strings.ToUpper(part[:1]) + part[1:]
		}
	}
	return strings.Join(parts, "")
}

// Overrides preserve Go integer storage, not the wire type. Validate the whole
// schema before either renderer can bypass an annotation via $ref or anyOf.
func (s schema) validateGoTypes(path string) error {
	if s.GoType != "" {
		switch s.GoType {
		case "uint64", "int64", "json.Number":
			if s.Type != "integer" || s.Ref != "" || len(s.AnyOf) != 0 || s.Const != nil || len(s.Enum) != 0 || s.Format != "" || s.Items != nil || len(s.Properties) != 0 {
				return fmt.Errorf("%s: incompatible x-go-type %q: requires a plain integer schema", path, s.GoType)
			}
		default:
			return fmt.Errorf("%s: unsupported Go type %s", path, s.GoType)
		}
	}
	for name, child := range s.Defs {
		if err := child.validateGoTypes(path + ".$defs." + name); err != nil {
			return err
		}
	}
	for name, child := range s.Properties {
		if err := child.validateGoTypes(path + "." + name); err != nil {
			return err
		}
	}
	if s.Items != nil {
		if err := s.Items.validateGoTypes(path + ".items"); err != nil {
			return err
		}
	}
	for i, child := range s.AnyOf {
		if err := child.validateGoTypes(fmt.Sprintf("%s.anyOf[%d]", path, i)); err != nil {
			return err
		}
	}
	return nil
}

func (doc schema) typeName(s schema, ts bool) (string, error) {
	if len(s.AnyOf) == 2 && s.AnyOf[1].Type == "null" {
		t, err := doc.typeName(s.AnyOf[0], ts)
		if ts {
			return t + " | null", err
		}
		return "*" + t, err
	}
	if !ts && s.GoPointer {
		s.GoPointer = false
		t, err := doc.typeName(s, false)
		return "*" + t, err
	}
	if !ts && s.GoType != "" {
		return s.GoType, nil // Validated before either language is generated.
	}
	if s.Ref != "" {
		name := strings.TrimPrefix(s.Ref, "#/$defs/")
		target, ok := doc.Defs[name]
		if !ok {
			return "", fmt.Errorf("unknown reference %s", s.Ref)
		}
		if ts {
			return name, nil
		}
		if target.GoName != "" {
			return target.GoName, nil
		}
		return doc.typeName(target, false)
	}
	if ts && (s.Const != nil || len(s.Enum) > 0) {
		values := s.Enum
		if s.Const != nil {
			values = []string{*s.Const}
		}
		quoted := make([]string, len(values))
		for i, value := range values {
			b, _ := json.Marshal(value)
			quoted[i] = string(b)
		}
		return strings.Join(quoted, " | "), nil
	}
	switch s.Type {
	case "string":
		if !ts && s.Format == "date-time" {
			return "time.Time", nil
		}
		return "string", nil
	case "boolean":
		if ts {
			return "boolean", nil
		}
		return "bool", nil
	case "integer":
		if ts {
			return "number", nil
		}
		return "int64", nil
	case "array":
		if s.Items != nil {
			t, err := doc.typeName(*s.Items, ts)
			if ts {
				return "(" + t + ")[]", err
			}
			return "[]" + t, err
		}
	}
	return "", fmt.Errorf("unsupported schema type %q", s.Type)
}
