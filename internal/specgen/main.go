// Command specgen copies spec/protocol/v1 into package delegate: the error
// catalog becomes Go constants and the vectors become test data. With -bridge
// it writes the upper-case refusals a bridge App may return as package
// bridge's refusals_gen.go instead; with -rust, the same refusals as the Rust
// App SDK's refusals.rs, and with -python as the Python App SDK's
// _refusals.py.
//
// Usage: specgen [-bridge|-rust|-python] <spec/protocol/v1> [output directory, default "."]
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"unicode"
)

func main() {
	args := os.Args[1:]
	generate := run
	if len(args) > 0 && args[0] == "-bridge" {
		args, generate = args[1:], generator("refusals_gen.go", bridgeRefusals)
	} else if len(args) > 0 && args[0] == "-rust" {
		args, generate = args[1:], generator("refusals.rs", rustRefusals)
	} else if len(args) > 0 && args[0] == "-python" {
		args, generate = args[1:], generator("_refusals.py", pythonRefusals)
	}
	if len(args) < 1 || len(args) > 2 {
		fmt.Fprintln(os.Stderr, "usage: specgen [-bridge|-rust|-python] <spec/protocol/v1> [out]")
		os.Exit(2)
	}
	out := "."
	if len(args) == 2 {
		out = args[1]
	}
	if err := generate(args[0], out); err != nil {
		fmt.Fprintln(os.Stderr, "specgen:", err)
		os.Exit(1)
	}
}

func run(spec, out string) error {
	b, err := os.ReadFile(filepath.Join(spec, "errors.json"))
	if err != nil {
		return err
	}
	src, err := constants(b)
	if err != nil {
		return err
	}
	if err = os.WriteFile(filepath.Join(out, "codes_gen.go"), src, 0644); err != nil {
		return err
	}
	return copyVectors(filepath.Join(spec, "vectors"), filepath.Join(out, "testdata", "vectors"))
}

// generator writes file from the catalog with source.
func generator(file string, source func([]byte) ([]byte, error)) func(spec, out string) error {
	return func(spec, out string) error {
		b, err := os.ReadFile(filepath.Join(spec, "errors.json"))
		if err != nil {
			return err
		}
		src, err := source(b)
		if err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(out, file), src, 0644)
	}
}

type entry struct {
	Code string `json:"code"`
	Kind string `json:"kind"`
	En   string `json:"en"`
}

func constants(catalog []byte) ([]byte, error) {
	var doc struct {
		Codes []entry `json:"codes"`
	}
	if err := json.Unmarshal(catalog, &doc); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by specgen from spec/protocol/v1/errors.json. DO NOT EDIT.\n\npackage delegate\n\n// Protocol v1 codes and operation reasons.\nconst (\n")
	seen := map[string]string{}
	for _, c := range doc.Codes {
		name := constName(c.Kind, c.Code)
		if other, dup := seen[name]; dup {
			return nil, fmt.Errorf("%s and %s both map to %s", other, c.Code, name)
		}
		seen[name] = c.Code
		fmt.Fprintf(&b, "\t// %s (%s): %s\n\t%s = %q\n", name, c.Kind, c.En, name, c.Code)
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

// upperCase is the form of the refusals an executor sends; the lower-case
// ones (not-found, queue-full) belong to SDK capabilities.
var upperCase = regexp.MustCompile(`^[A-Z][A-Z0-9_]{0,63}$`)

// refusals are the catalog's upper-case refusal and client codes, the ones a
// bridge App may return: an executor's refusal, or what the runtime's
// executor client said instead of a reply (APP_STOPPED, for a stopped package).
func refusals(catalog []byte) ([]entry, error) {
	var doc struct {
		Codes []entry `json:"codes"`
	}
	if err := json.Unmarshal(catalog, &doc); err != nil {
		return nil, err
	}
	var out []entry
	for _, c := range doc.Codes {
		if (c.Kind == "refusal" || c.Kind == "client") && upperCase.MatchString(c.Code) {
			out = append(out, c)
		}
	}
	return out, nil
}

// bridgeRefusals is the set of upper-case refusal and client codes, for
// package bridge.
func bridgeRefusals(catalog []byte) ([]byte, error) {
	codes, err := refusals(catalog)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by specgen from spec/protocol/v1/errors.json. DO NOT EDIT.\n\npackage bridge\n\n// protocolRefusals are the upper-case refusal and client codes of protocol\n// v1. An App may return them, so the browser's SDK can translate them.\nvar protocolRefusals = map[string]bool{\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "\t%q: true,\n", c.Code)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// pythonRefusals is the same set for the Python App SDK.
func pythonRefusals(catalog []byte) ([]byte, error) {
	codes, err := refusals(catalog)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("# Code generated by specgen from spec/protocol/v1/errors.json. DO NOT EDIT.\n\n# The upper-case refusal and client codes of protocol v1. An App may return\n# them, so the browser's SDK can translate them.\nREFUSALS = frozenset(\n    {\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "        %q,\n", c.Code)
	}
	b.WriteString("    }\n)\n")
	return b.Bytes(), nil
}

// rustRefusals is the same set as Rust constants, in rustfmt's layout.
func rustRefusals(catalog []byte) ([]byte, error) {
	codes, err := refusals(catalog)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by specgen from spec/protocol/v1/errors.json. DO NOT EDIT.\n\n//! The upper-case refusal and client codes of protocol v1. A service refusal\n//! may carry one, and an App may return it, so the browser's SDK can\n//! translate it.\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "\n/// %s\npub const %s: &str = %q;\n", c.En, c.Code, c.Code)
	}
	return b.Bytes(), nil
}

// constName turns AUTH_DENIED and operation-not-found into CodeAuthDenied
// and CodeOperationNotFound; an operation reason such as grant-revoked
// becomes ReasonGrantRevoked, since reasons are a separate field.
func constName(kind, code string) string {
	var b strings.Builder
	if kind == "reason" {
		b.WriteString("Reason")
	} else {
		b.WriteString("Code")
	}
	for _, word := range words(code) {
		lower := strings.ToLower(word)
		b.WriteRune(unicode.ToUpper(rune(lower[0])))
		b.WriteString(lower[1:])
	}
	return b.String()
}

// words splits AUTH_DENIED and operation-not-found at '_' and '-'.
func words(code string) []string {
	return strings.FieldsFunc(code, func(r rune) bool { return r == '_' || r == '-' })
}

func copyVectors(from, to string) error {
	if err := os.RemoveAll(to); err != nil {
		return err
	}
	if err := os.MkdirAll(to, 0755); err != nil {
		return err
	}
	files, err := filepath.Glob(filepath.Join(from, "*.jsonl"))
	if err != nil {
		return err
	}
	if len(files) == 0 {
		return fmt.Errorf("no vectors in %s", from)
	}
	for _, file := range files {
		b, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		if err = os.WriteFile(filepath.Join(to, filepath.Base(file)), b, 0644); err != nil {
			return err
		}
	}
	return nil
}
