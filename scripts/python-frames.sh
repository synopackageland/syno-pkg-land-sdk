#!/usr/bin/env bash
# Writes python/synopkgland_app/frames.pyi, the TypedDicts of every bridge
# frame, from spec/bridge/v1/frames.schema.json. A stub: type checkers read
# it, and an App never imports it at run time, so DSM's Python needs no
# typing_extensions. With --check, fails when the committed stub differs.
# Needs uv; the generator runs at build time only.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
schema=spec/bridge/v1/frames.schema.json
stub=python/synopkgland_app/frames.pyi
generator=datamodel-code-generator==0.83.0

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cd "$root"
digest=$(shasum -a 256 "$schema" | cut -d ' ' -f 1)
{
	echo "# Code generated by scripts/python-frames.sh from $schema with $generator. DO NOT EDIT."
	echo "# schema sha256 $digest"
	echo
	uvx --quiet --python 3.12 --from "$generator" datamodel-codegen \
		--input "$schema" --input-file-type jsonschema \
		--output-model-type typing.TypedDict --target-python-version 3.10 \
		--no-use-closed-typed-dict --no-use-union-operator --no-use-standard-collections \
		--formatters builtin --disable-timestamp |
		# typing.TypeAlias is 3.10; checkers of 3.8 and 3.9 code take it from typing_extensions.
		sed -e 's/^\(from typing import .*\), TypeAlias,/\1,/' \
			-e 's/^from typing_extensions import NotRequired$/from typing_extensions import NotRequired, TypeAlias/'
} >"$tmp/frames.pyi"

if test "${1:-}" = --check; then
	if ! cmp -s "$tmp/frames.pyi" "$stub"; then
		echo "$stub is stale; run scripts/python-frames.sh" >&2
		diff -u "$stub" "$tmp/frames.pyi" >&2 || true
		exit 1
	fi
else
	cp "$tmp/frames.pyi" "$stub"
fi
