// The shipped executor's slot constant is authoritative. Generate the client
// limit from its unchanged source so client-only releases can reuse that binary.
import {readFileSync, writeFileSync} from 'node:fs';
const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('executor/root_run.go', root), 'utf8');
const slots = /^\s*rootRunSlots\s*=\s*([1-9]\d*)\s*$/m.exec(source)?.[1];
if (!slots) throw Error('Cannot read executor root slot count');
const target = new URL('delegate/admission_limits_gen.go', root);
const content = `// Code generated by scripts/admission-limits.mjs from executor/root_run.go. DO NOT EDIT.\npackage delegate\n\nconst executorRootSlots = ${slots}\n`;
if (process.argv.includes('--check')) {
 if (readFileSync(target, 'utf8') !== content) throw Error('Delegate admission limit differs from executor; regenerate it');
} else writeFileSync(target, content);
