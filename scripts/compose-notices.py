#!/usr/bin/env python3
"""Generate the full terms for modules linked into the SDK Compose control.
Run at the SDK root after go mod download; review changes with dependency bumps.
"""
import json
import pathlib
import subprocess

modules = {}
raw = subprocess.check_output(['go', 'list', '-deps', '-json', './compose/cmd/plan'], text=True)
decoder = json.JSONDecoder()
while raw.strip():
    item, end = decoder.raw_decode(raw.lstrip())
    raw = raw.lstrip()[end:]
    module = item.get('Module', {})
    if module.get('Version'):
        modules[module['Path']] = module
output = ['SDK Compose control: dependency terms. Generated by scripts/compose-notices.py.\n']
for name, module in sorted(modules.items()):
    output.append('\n' + '=' * 72 + '\n' + name + ' ' + module['Version'] + '\n')
    root = pathlib.Path(module['Dir'])
    files = [p for p in root.iterdir() if p.is_file() and p.name.upper().startswith(('LICENSE', 'COPYING', 'NOTICE', 'PATENTS', 'COPYRIGHT'))]
    if not files:
        raise SystemExit('Missing terms: ' + name)
    for path in sorted(files):
        output.extend(['\n--- ' + path.name + ' ---\n', path.read_text()])
pathlib.Path('compose/THIRD_PARTY_NOTICES.txt').write_text(''.join(output))
