// Generate transport bounds from the single protocol limit definition.
import {readFileSync, writeFileSync} from 'node:fs';
const root = new URL('../', import.meta.url);
const {webapi_reply_bytes: reply, reply_envelope_bytes: envelope} = JSON.parse(readFileSync(new URL('spec/protocol/v1/limits.json', root)));
if (![reply, envelope].every(n => Number.isSafeInteger(n) && n > 0)) throw Error('Invalid protocol limits');
const go = `// Code generated by scripts/protocol-limits.mjs. DO NOT EDIT.\npackage wirelimits\n\nconst MaxWebAPIReply = ${reply}\nconst MaxReplyFrame = MaxWebAPIReply + ${envelope}\n`;
const files = {
 'internal/wirelimits/limits.go': go,
 'executor/internal/wirelimits/limits.go': go,
 'ts/src/protocol/limits.ts': `// Generated by scripts/protocol-limits.mjs. DO NOT EDIT.\nexport const MAX_WEBAPI_REPLY = ${reply}\nexport const MAX_REPLY_FRAME = MAX_WEBAPI_REPLY + ${envelope}\n`,
 'node/src/limits.ts': `// Generated by scripts/protocol-limits.mjs. DO NOT EDIT.\nexport const MAX_WEBAPI_REPLY = ${reply}\nexport const MAX_REPLY_FRAME = MAX_WEBAPI_REPLY + ${envelope}\n`,
 'python/synopkgland_app/_limits.py': `# Generated by scripts/protocol-limits.mjs. DO NOT EDIT.\nMAX_WEBAPI_REPLY = ${reply}\nMAX_REPLY_FRAME = MAX_WEBAPI_REPLY + ${envelope}\n`,
};
for (const [name, content] of Object.entries(files)) {
 if (process.argv.includes('--check')) {
  if (readFileSync(new URL(name, root), 'utf8') !== content) throw Error(`${name} is stale`);
 } else writeFileSync(new URL(name, root), content);
}
