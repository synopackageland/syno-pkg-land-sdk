#!/usr/bin/env node
// Generate src/protocol/v1.ts from spec/protocol/v1 (errors.json and schema/).
// Usage: node scripts/gen-protocol.mjs [spec dir] [out file]
import {readFileSync,readdirSync,writeFileSync} from 'node:fs'
import {dirname,resolve} from 'node:path'
import {fileURLToPath} from 'node:url'

const here=dirname(fileURLToPath(import.meta.url))
const pascal=op=>op.split(/[._]/).map(p=>p[0].toUpperCase()+p.slice(1)).join('')
const literal=value=>JSON.stringify(value)
function type(schema,depth=1){
 if('const' in schema)return literal(schema.const)
 if(schema.enum)return schema.enum.map(literal).join(' | ')
 if(schema.type==='array')return `${type(schema.items,depth)}[]`
 if(schema.type==='integer'||schema.type==='number')return 'number'
 if(schema.type==='string'||schema.type==='boolean')return schema.type
 // An object without properties is free-form, such as root params a policy schema checks.
 if(schema.type==='object'&&!schema.properties)return 'Record<string, unknown>'
 if(schema.type==='object'&&schema.properties)return [
  '{',
  ...Object.entries(schema.properties).map(([name,prop])=>`${' '.repeat(depth+1)}${/^[A-Za-z_$][\w$]*$/.test(name)?name:literal(name)}${schema.required?.includes(name)?'':'?'}: ${type(prop,depth+1)}`),
  `${' '.repeat(depth)}}`,
 ].join('\n')
 throw Error(`unsupported schema ${JSON.stringify(schema)}`)
}

/** The generated module for the spec directory, as a string. */
export function generate(spec){
 const codes=JSON.parse(readFileSync(resolve(spec,'errors.json'),'utf8')).codes
 const schemas=readdirSync(resolve(spec,'schema')).filter(f=>f.endsWith('.json')).sort()
  .map(f=>JSON.parse(readFileSync(resolve(spec,'schema',f),'utf8')))
 const out=['// Code generated by scripts/gen-protocol.mjs from spec/protocol/v1. DO NOT EDIT.','']
 out.push('/** Every protocol v1 code with its kind, whether a retry may succeed, and the HTTP status an adapter should use. */')
 out.push('export const protocolCodes = {')
 for(const c of codes)out.push(` /** ${c.en} */`,` ${literal(c.code)}: {kind: ${literal(c.kind)}, retryable: ${c.retryable}, httpStatus: ${c.httpStatus}},`)
 out.push('} as const','export type ProtocolCode = keyof typeof protocolCodes')
 for(const kind of ['refusal','outcome','reason','client']){
  out.push(`export type ${kind[0].toUpperCase()+kind.slice(1)}Code = ${codes.filter(c=>c.kind===kind).map(c=>literal(c.code)).join(' | ')}`)
 }
 out.push('')
 for(const s of schemas){
  out.push(`/** ${s.title}: ${s.description} Since ${s.since}. */`,`export interface ${pascal(s.title)}Params {`)
  for(const [name,prop] of Object.entries(s.properties))out.push(` ${name}${s.required?.includes(name)?'':'?'}: ${type(prop)}`)
  out.push('}')
 }
 out.push('','/** The params of each op. */','export interface ProtocolParams {')
 for(const s of schemas)out.push(` ${literal(s.title)}: ${pascal(s.title)}Params`)
 out.push('}','export type ProtocolOp = keyof ProtocolParams','')
 out.push('/** Each op\'s auth requirement and its params, all and required. */')
 out.push('export const protocolSchemas: {readonly [Op in ProtocolOp]: {readonly auth: \'required\' | \'optional\'; readonly params: readonly (keyof ProtocolParams[Op])[]; readonly required: readonly (keyof ProtocolParams[Op])[]}} = {')
 for(const s of schemas)out.push(` ${literal(s.title)}: {auth: ${literal(s.auth)}, params: ${literal(Object.keys(s.properties))}, required: ${literal(s.required??[])}},`)
 out.push('}','export const protocolOps = Object.keys(protocolSchemas) as ProtocolOp[]','')
 return out.join('\n')
}

if(process.argv[1]===fileURLToPath(import.meta.url)){
 const spec=resolve(process.argv[2]??resolve(here,'../../spec/protocol/v1'))
 writeFileSync(process.argv[3]??resolve(here,'../src/protocol/v1.ts'),generate(spec))
}
